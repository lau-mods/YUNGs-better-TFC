package net.claustra01.yungsbettertfc.datagen;

import java.io.IOException;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.mojang.serialization.JsonOps;

import net.claustra01.yungsbettertfc.YungsBetterTfc;
import net.claustra01.yungsbettertfc.loot.StructureLootModifier;
import net.claustra01.yungsbettertfc.loot.StructureLootRules;
import net.claustra01.yungsbettertfc.loot.StructureLootRules.Profile;
import net.minecraft.core.HolderLookup;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.core.registries.Registries;
import net.minecraft.data.tags.TagsProvider;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.tags.TagKey;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.Items;
import net.minecraft.world.level.storage.loot.functions.LootItemFunction;
import net.minecraft.world.level.storage.loot.functions.LootItemFunctions;
import net.minecraft.world.level.storage.loot.predicates.LootItemCondition;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.ModList;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.neoforge.common.data.GlobalLootModifierProvider;
import net.neoforged.neoforge.common.loot.LootTableIdCondition;
import net.neoforged.neoforge.data.event.GatherDataEvent;

/** Registers the server data generated by {@code ./gradlew runData}. */
@EventBusSubscriber(modid = YungsBetterTfc.MOD_ID)
public final class DataGenerators {
    /** Structure chest tables converted by {@link StructureLootModifier}; Overdims handles Nether Bridge and End City. */
    private static final Map<String, List<String>> TARGET_TABLES = new TreeMap<>(Map.of(
            "betterdungeons", List.of(
                    "skeleton_dungeon/chests/common", "skeleton_dungeon/chests/middle",
                    "small_dungeon/chests/loot_piles", "small_nether_dungeon/chests/common",
                    "spider_dungeon/chests/egg_room", "zombie_dungeon/chests/common",
                    "zombie_dungeon/chests/special", "zombie_dungeon/chests/tombstone"),
            "betterfortresses", List.of(
                    "chests/beacon", "chests/extra", "chests/hall", "chests/keep", "chests/obsidian",
                    "chests/puzzle", "chests/quarters", "chests/storage", "chests/worship"),
            "betteroceanmonuments", List.of("chests/upper_side_chamber"),
            "betterstrongholds", List.of(
                    "chests/armoury", "chests/cmd_yung", "chests/common", "chests/crypt",
                    "chests/grand_library", "chests/library_md", "chests/mess", "chests/prison_lg",
                    "chests/trap", "chests/treasure"),
            "minecraft", List.of(
                    "chests/abandoned_mineshaft", "chests/simple_dungeon", "chests/stronghold_corridor",
                    "chests/stronghold_crossing", "chests/stronghold_library")));
    private static final Map<TagKey<Item>, List<String>> LOOT_TAGS = lootTags();
    private static final Set<String> ENCHANTMENT_FUNCTIONS = Set.of(
            "minecraft:enchant_randomly", "minecraft:enchant_with_levels", "minecraft:set_enchantments");

    private DataGenerators() {}

    @SubscribeEvent
    public static void gatherData(GatherDataEvent event) {
        var output = event.getGenerator().getPackOutput();
        var registries = event.getLookupProvider();
        event.getGenerator().addProvider(event.includeServer(),
                new GlobalLootModifierProvider(output, registries, YungsBetterTfc.MOD_ID) {
                    @Override
                    protected void start() {
                        TARGET_TABLES.forEach((namespace, paths) -> paths.forEach(path -> {
                            ResourceLocation table = ResourceLocation.fromNamespaceAndPath(namespace, path);
                            add(namespace + "/" + path, new StructureLootModifier(
                                    new LootItemCondition[] {LootTableIdCondition.builder(table).build()},
                                    profile(namespace, path), enchantments(table, registries), fixed(table)));
                        }));
                    }
                });
        event.getGenerator().addProvider(event.includeServer(), new TagsProvider<Item>(
                output, Registries.ITEM, registries, YungsBetterTfc.MOD_ID, event.getExistingFileHelper()) {
            @Override
            protected void addTags(HolderLookup.Provider provider) {
                LOOT_TAGS.forEach((tag, members) -> {
                    var appender = tag(tag);
                    members.forEach(member -> appender.add(ResourceKey.create(Registries.ITEM,
                            ResourceLocation.fromNamespaceAndPath("tfc", member))));
                });
            }
        });
    }

    /**
     * Reads the pristine source table from its own mod file and returns the enchantment functions of its equipment
     * item entries. An item whose entries use different enchantment functions is omitted, so its enchanted stacks
     * stay unchanged.
     */
    private static Map<ResourceLocation, LootItemFunction> enchantments(ResourceLocation table, HolderLookup.Provider registries) {
        var info = ModList.get().getModFileById(table.getNamespace());
        if (info == null || info == ModList.get().getModFileById(YungsBetterTfc.MOD_ID)) {
            throw new IllegalStateException("Loot generation requires the pristine " + table.getNamespace() + " mod file");
        }
        Path path = info.getFile().findResource("data", table.getNamespace(), "loot_table", table.getPath() + ".json");
        Map<ResourceLocation, Set<JsonElement>> found = new TreeMap<>();
        try (Reader reader = Files.newBufferedReader(path, StandardCharsets.UTF_8)) {
            JsonObject source = JsonParser.parseReader(reader).getAsJsonObject();
            if (source.has("pools")) {
                for (JsonElement pool : source.getAsJsonArray("pools")) {
                    pool.getAsJsonObject().getAsJsonArray("entries").forEach(entry -> collect(entry.getAsJsonObject(), found));
                }
            }
        } catch (IOException exception) {
            throw new IllegalStateException("Unable to read source loot table " + table, exception);
        }
        Map<ResourceLocation, LootItemFunction> result = new TreeMap<>();
        found.forEach((item, functions) -> {
            if (functions.size() == 1) {
                result.put(item, LootItemFunctions.ROOT_CODEC
                        .parse(registries.createSerializationContext(JsonOps.INSTANCE), functions.iterator().next())
                        .getOrThrow(error -> new IllegalStateException("Invalid enchantment function in " + table + ": " + error)));
            }
        });
        return result;
    }

    private static void collect(JsonObject entry, Map<ResourceLocation, Set<JsonElement>> found) {
        if (entry.has("children")) {
            entry.getAsJsonArray("children").forEach(child -> collect(child.getAsJsonObject(), found));
        }
        if (!entry.has("type") || !entry.get("type").getAsString().equals("minecraft:item")) {
            return;
        }
        ResourceLocation item = ResourceLocation.parse(entry.get("name").getAsString());
        if (!StructureLootRules.isEquipment(BuiltInRegistries.ITEM.get(item)) || !entry.has("functions")) {
            return;
        }
        JsonArray functions = new JsonArray();
        for (JsonElement function : entry.getAsJsonArray("functions")) {
            if (ENCHANTMENT_FUNCTIONS.contains(function.getAsJsonObject().get("function").getAsString())) {
                functions.add(function);
            }
        }
        if (!functions.isEmpty()) {
            found.computeIfAbsent(item, key -> new HashSet<>()).add(functions.size() == 1 ? functions.get(0) : functions);
        }
    }

    /** Better Strongholds' named special sword always becomes a finished TFC sword of its Dangerous tier. */
    private static Map<Item, Item> fixed(ResourceLocation table) {
        if (!table.toString().equals("betterstrongholds:chests/cmd_yung")) {
            return Map.of();
        }
        ResourceLocation sword = ResourceLocation.parse("tfc:metal/sword/wrought_iron");
        return Map.of(Items.DIAMOND_SWORD, BuiltInRegistries.ITEM.getOptional(sword)
                .orElseThrow(() -> new IllegalStateException("Loot generation references unregistered item " + sword)));
    }

    private static Profile profile(String namespace, String path) {
        // Better Strongholds places Vanilla stronghold chests, so they share its Dangerous tier.
        if (namespace.equals("betterfortresses") || namespace.equals("betterstrongholds")
                || (namespace.equals("betterdungeons") && path.startsWith("small_nether_dungeon/"))
                || (namespace.equals("minecraft") && path.startsWith("chests/stronghold_"))) {
            return Profile.DANGEROUS;
        }
        return Profile.ORDINARY;
    }

    private static Map<TagKey<Item>, List<String>> lootTags() {
        Map<TagKey<Item>, List<String>> result = new LinkedHashMap<>();
        result.put(StructureLootRules.FERTILIZERS, Arrays.asList(
                "compost", "rotten_compost", "powder/wood_ash", "powder/saltpeter",
                "powder/sylvite", "groundcover/guano"));
        return result;
    }
}
